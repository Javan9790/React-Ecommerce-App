export function getProducts() {
  try {
    const saved = localStorage.getItem("shopProducts");
    return saved ? JSON.parse(saved) : products;
  } catch {
    return products;
  }
}

export function saveProducts(updatedProducts) {
  localStorage.setItem("shopProducts", JSON.stringify(updatedProducts));
}

export function getProductById(id) {
  return getProducts().find((product) => product.id === Number(id));
}